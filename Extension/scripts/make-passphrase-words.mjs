// Writes src/shared/passphrase-words.js from Core's EFF large wordlist (core/src/wordlist/eff_large.txt),
// so passphrases made in the page use the same 7,776 words as the core's `generate_passphrase`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = new URL('../../Core/core/src/wordlist/eff_large.txt', import.meta.url);
const target = `${root}src/shared/passphrase-words.js`;

const words = readFileSync(source, 'utf8').split(/\r?\n/).map((w) => w.trim()).filter(Boolean);
if (words.length !== 7776) throw new Error(`expected 7776 words, found ${words.length}`);
for (const w of words) if (!/^[a-z-]+$/.test(w)) throw new Error(`unexpected word: ${w}`);

const lines = [];
let line = '';
for (const w of words) {
  if (line && line.length + 1 + w.length > 110) { lines.push(line); line = w; } else line = line ? `${line} ${w}` : w;
}
if (line) lines.push(line);

writeFileSync(target, `// Generated by scripts/make-passphrase-words.mjs from Core/core/src/wordlist/eff_large.txt: do not edit.
// The EFF large wordlist (https://www.eff.org/dice), by the Electronic Frontier Foundation, CC BY 3.0 US
// (THIRD_PARTY_NOTICES.md). 7,776 words for passphrases made in the page (content/gen-options.js).
export const PASSPHRASE_WORDS = \`
${lines.join('\n')}
\`;
`);
console.log(`wrote ${words.length} words to src/shared/passphrase-words.js`);
